// Pixel sidebar icons on an 11x11 grid ('#' = lit cell). Drawn at 22px so each cell is 2x2 px
// Only render at multiples of 11 or they go blurry
const pixels = (rows: string[]) => {
  let d = "";
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  const t = document.createElement("template");
  t.innerHTML = `<svg viewBox="0 0 11 11" fill="currentColor" shape-rendering="crispEdges"><path d="${d}"/></svg>`;
  return t.content.firstChild as SVGElement;
};
